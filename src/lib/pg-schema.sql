-- InvoiceFlow PostgreSQL schema (translated from SQLite inventory in src/lib/db.ts).
-- Idempotent: safe to run on every boot via CREATE IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  name TEXT NOT NULL,
  company_name TEXT,
  created_at TEXT DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Hong_Kong', 'YYYY-MM-DD HH24:MI:SS')),
  role TEXT NOT NULL DEFAULT 'admin',
  owner_user_id INTEGER REFERENCES users(id)
);

