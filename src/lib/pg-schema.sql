-- Org-wide inbound: child-user rows belong to the admin data pool.
UPDATE inbound_shipments s
SET user_id = u.owner_user_id
FROM users u
WHERE s.user_id = u.id
  AND u.owner_user_id IS NOT NULL
  AND s.user_id <> u.owner_user_id;

